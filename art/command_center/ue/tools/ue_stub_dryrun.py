#!/usr/bin/env python3
"""Dry run of a UE editor import script outside Unreal (default: ue_import_command_center.py; any other with --script,
e.g. ../../base_nodes/ue/ue_import_base_nodes.py), validated against the generated UE Python stub.

The stub (unreal.py, ~25 MB) is what the editor writes with "Developer Mode" on; the PyPI package unreal-stub 0.3 ships
the one generated by UE 5.6.0. It is PARSED (ast), never imported. A fake `unreal` module is then installed and the
import script runs all four modes; every access is checked:

  * unreal.<Name>                    class / function / enum exists in 5.6
  * Class.method(...) / obj.method() method exists on the class or a base; positional / keyword arguments fit
  * set/get_editor_property(name)    name is an editor property of the class or a base (docstring list of the stub)
  * Struct(kw=...)                    keyword names are editor properties of the struct
  * Enum.VALUE                        value exists

FactoryGame / mod objects (game classes from load_class, their CDOs, ItemAmount, SchematicType) are not in the engine
stub: they are permissive and every property set on them is listed, so it can be compared with the SML headers.

    pip download --no-deps unreal-stub==0.3 && unzip the wheel  (or use the editor's Intermediate/PythonStub/unreal.py)
    python3 tools/ue_stub_dryrun.py --stub <path>/unreal/unreal.py [--work <scratch dir>]
    python3 tools/ue_stub_dryrun.py --stub ... --script ../../base_nodes/ue/ue_import_base_nodes.py \
            --modes=--import,--table,--verify --compiled-modes=--table

Exit code 1 if any API mismatch was found. The import script runs on a copy (in --work) so the repo stays clean.
"""
import argparse
import ast
import json
import os
import pickle
import re
import shutil
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
UE_DIR = os.path.normpath(os.path.join(HERE, ".."))
ART = os.path.normpath(os.path.join(UE_DIR, ".."))
GAME_NAMES = {"ItemAmount", "SchematicType"}          # FactoryGame types reached through `unreal.` (not in the stub)

PROP_RE = re.compile(r"^\s*- ``(\w+)`` \(([^)]*)\)", re.M)


# ------------------------------------------------------------------------------------------------------- stub index
def build_index(stub):
    cache = stub + ".index.pickle"
    if os.path.exists(cache) and os.path.getmtime(cache) >= os.path.getmtime(stub):
        return pickle.load(open(cache, "rb"))
    src = open(stub, encoding="utf-8-sig").read()
    classes, funcs = {}, {}
    # The generated stub is not valid Python as a whole (some Slate struct defaults are printed verbatim), so it is
    # split into top-level blocks; a block that does not parse is read with regular expressions (names only).
    starts = [m.start() for m in re.finditer(r"^(?:class |def |@)", src, re.M)] + [len(src)]
    blocks, i = [], 0
    while i < len(starts) - 1:
        j = i
        while src[starts[j]] == "@" and j < len(starts) - 2:       # decorators belong to the next def / class
            j += 1
        blocks.append(src[starts[i]:starts[j + 1]])
        i = j + 1
    regex_blocks = 0

    def sig(fn, skip_first):
        a = fn.args
        names = [x.arg for x in a.posonlyargs + a.args][1 if skip_first else 0:]
        return {"args": names, "ndefaults": len(a.defaults), "kwonly": [x.arg for x in a.kwonlyargs],
                "varargs": a.vararg is not None, "varkw": a.kwarg is not None,
                "ret": ast.unparse(fn.returns) if fn.returns else "Any"}

    for block in blocks:
        try:
            body = ast.parse(block).body
        except SyntaxError:
            regex_blocks += 1
            m = re.match(r"class (\w+)\(([^)]*)\)", block)
            if not m:
                fm = re.match(r"def (\w+)\(", block)
                if fm:
                    funcs[fm.group(1)] = None
                continue
            c = {"bases": [x.strip() for x in m.group(2).split(",") if x.strip()], "methods": {}, "props": {},
                 "enum": set(re.findall(r"^    (\w+): \w+ = \.\.\.", block, re.M))}
            for name, typ in PROP_RE.findall(block):
                c["props"].setdefault(name, typ.strip())
            for name in re.findall(r"^    def (\w+)\(", block, re.M):
                c["methods"].setdefault(name, None)                 # signature unknown: arguments not checked
            classes[m.group(1)] = c
            continue
        for node in body:
            if isinstance(node, ast.ClassDef):
                c = {"bases": [ast.unparse(b) for b in node.bases], "methods": {}, "props": {}, "enum": set()}
                doc = ast.get_docstring(node) or ""
                for name, typ in PROP_RE.findall(doc):
                    c["props"][name] = typ.strip()
                for item in node.body:
                    if isinstance(item, ast.FunctionDef):
                        decos = [ast.unparse(d) for d in item.decorator_list]
                        if "property" in decos:
                            c["props"].setdefault(item.name, ast.unparse(item.returns) if item.returns else "Any")
                        elif not any(d.endswith(".setter") for d in decos):
                            c["methods"][item.name] = sig(item, "staticmethod" not in decos)
                    elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                        c["enum"].add(item.target.id)
                    elif isinstance(item, ast.Assign):
                        for t in item.targets:
                            if isinstance(t, ast.Name):
                                c["enum"].add(t.id)
                classes[node.name] = c
            elif isinstance(node, ast.FunctionDef):
                funcs[node.name] = sig(node, False)
    print(f"stub index: {len(blocks)} blocks, {regex_blocks} read by regex")
    idx = {"classes": classes, "funcs": funcs}
    pickle.dump(idx, open(cache, "wb"))
    return idx


# ------------------------------------------------------------------------------------------------------- fake unreal
class Report:
    def __init__(self):
        self.errors, self.game_props, self.calls = [], [], set()

    def err(self, msg):
        if msg not in self.errors:
            self.errors.append(msg)


class Fake:
    def __init__(self, idx, rep):
        self.idx, self.rep = idx, rep

    # --- index helpers
    def mro(self, cls):
        out, todo = [], [cls]
        while todo:
            c = todo.pop(0)
            if c in out or c not in self.idx["classes"]:
                continue
            out.append(c)
            todo.extend(b.split("[")[0] for b in self.idx["classes"][c]["bases"])
        return out

    def find_method(self, cls, name):
        for c in self.mro(cls):
            ms = self.idx["classes"][c]["methods"]
            if name in ms:
                return ms[name] or {"args": [], "ndefaults": 0, "kwonly": [], "varargs": True, "varkw": True,
                                    "ret": "Any"}
        return None

    def find_prop(self, cls, name):
        for c in self.mro(cls):
            t = self.idx["classes"][c]["props"].get(name)
            if t:
                return t
        return None

    def check_args(self, where, s, args, kwargs):
        n = len(args)
        if not s["varargs"] and n > len(s["args"]):
            self.rep.err(f"{where}: {n} positional args, signature takes {len(s['args'])} ({', '.join(s['args'])})")
        required = s["args"][:len(s["args"]) - s["ndefaults"]]
        given = set(s["args"][:n]) | set(kwargs)
        for k in kwargs:
            if k not in s["args"] and k not in s["kwonly"] and not s["varkw"]:
                self.rep.err(f"{where}: unknown keyword '{k}' (signature: {', '.join(s['args'])})")
        for r in required:
            if r not in given:
                self.rep.err(f"{where}: missing argument '{r}'")

    # --- values
    def value(self, ann, label=""):
        ann = (ann or "Any").strip().strip("'\"")
        m = re.match(r"(Optional|Array|List|Set|Union)\[(.*)\]$", ann)
        if m:
            inner = m.group(2).split(",")[0].strip()
            if m.group(1) in ("Array", "List", "Set"):
                return [self.value(inner, label)]
            return self.value(inner, label)
        if ann in ("bool",):
            return True
        if ann in ("int", "int32", "int64", "uint8", "uint32"):
            return 1
        if ann in ("float", "double"):
            return 1.0
        if ann in ("str", "Name", "Text", "String"):
            return "dry_" + (label or "x")
        if ann == "None":
            return None
        if ann in ("Any", "Object", "_T") or ann not in self.idx["classes"]:
            return Obj(self, "Object", permissive=True, label=label or ann)
        return Obj(self, ann, label=label)


class Callable_:
    def __init__(self, fake, where, s, impl=None, owner=None):
        self.fake, self.where, self.s, self.impl, self.owner = fake, where, s, impl, owner

    def __call__(self, *args, **kwargs):
        self.fake.rep.calls.add(self.where)
        if self.s:
            self.fake.check_args(self.where, self.s, args, kwargs)
        if self.impl:
            return self.impl(*args, **kwargs)
        return self.fake.value(self.s["ret"] if self.s else "Any", self.where.split(".")[-1])


class Cls:
    """unreal.<Class>: classmethods, enum values, constructor (structs take editor properties as keywords)."""

    def __init__(self, fake, name, permissive=False):
        self._f, self._name, self._perm = fake, name, permissive

    def __call__(self, *args, **kwargs):
        if not self._perm:
            for k in kwargs:
                if not self._f.find_prop(self._name, k):
                    self._f.rep.err(f"unreal.{self._name}({k}=...): no such property")
        o = Obj(self._f, self._name, permissive=self._perm)
        for k, v in kwargs.items():
            o._props[k] = v
        return o

    def __getattr__(self, a):
        if a.startswith("__"):
            raise AttributeError(a)
        if self._perm:
            return Obj(self._f, "Object", permissive=True, label=f"{self._name}.{a}")
        f = self._f
        for c in f.mro(self._name):
            if a in f.idx["classes"][c]["enum"]:
                return Obj(f, self._name, label=a)
        s = f.find_method(self._name, a)
        if s is None:
            if a == "static_class":
                return lambda: Obj(f, "Class", label=self._name)
            f.rep.err(f"unreal.{self._name}.{a}: not in UE 5.6")
            raise AttributeError(a)
        return Callable_(f, f"{self._name}.{a}", s, impl=SCENARIO.get(f"{self._name}.{a}") and
                         (lambda *x, _n=f"{self._name}.{a}", **k: SCENARIO[_n](f, *x, **k)))

    def get_path_name(self):
        return "/Script/Engine." + self._name


class Obj:
    def __init__(self, fake, cls, permissive=False, label=""):
        self.__dict__.update(_f=fake, _cls=cls, _perm=permissive, _label=label, _props={})

    def __repr__(self):
        return f"<{self._cls} {self._label}>"

    def __bool__(self):
        return True

    def __eq__(self, other):
        return self is other

    def __hash__(self):
        return id(self)

    def __getattr__(self, a):
        if a.startswith("__"):
            raise AttributeError(a)
        f = self._f
        if a == "set_editor_property":
            return self._set
        if a == "get_editor_property":
            return self._get
        if self._perm:
            if a in ("get_path_name", "get_name"):
                return lambda: self._label or "dry_object"
            return Callable_(f, f"<game>.{a}", None)
        s = f.find_method(self._cls, a)
        if s is not None:
            key = f"{self._cls}.{a}"
            impl = SCENARIO.get(key)
            return Callable_(f, key, s, impl=impl and (lambda *x, **k: impl(f, self, *x, **k)))
        t = f.find_prop(self._cls, a)
        if t is not None:
            return self._props.get(a, f.value(t, a))
        f.rep.err(f"{self._cls}.{a}: no such method / property in UE 5.6")
        raise AttributeError(a)

    def _set(self, name, value, *rest):
        f = self._f
        if self._perm:
            f.rep.game_props.append(f"{self._label}.{name}")
            self._props[name] = value
            return
        if not f.find_prop(self._cls, name):
            f.rep.err(f"{self._cls}.set_editor_property('{name}'): no such editor property in UE 5.6")
            raise Exception(f"Failed to find property '{name}'")
        self._props[name] = value

    def _get(self, name):
        f = self._f
        if name in self._props:
            return self._props[name]
        if self._perm:
            return Obj(f, "Object", permissive=True, label=f"{self._label}.{name}")
        t = f.find_prop(self._cls, name)
        if t is None:
            f.rep.err(f"{self._cls}.get_editor_property('{name}'): no such editor property in UE 5.6")
            raise Exception(f"Failed to find property '{name}'")
        if self._cls == "AssetImportTask" and name == "imported_object_paths":
            return [self._props.get("destination_path", "/Game") + "/" + self._props.get("destination_name", "x")]
        return f.value(t, name)


def _typed_by_path(f, path):
    p = str(path)
    if "/Mesh/" in p:
        return Obj(f, "StaticMesh", label=p)
    if "/Texture/" in p or "/Icon/" in p or p.startswith("/Engine/"):
        return Obj(f, "Texture2D", label=p)
    if "/MM_" in p:
        return Obj(f, "Material", label=p)
    if "/DT_" in p:
        return Obj(f, "DataTable", label=p)
    if "/MI_" in p:
        return Obj(f, "MaterialInstanceConstant", label=p)
    if "/FactoryGame/" in p or p.endswith("_C"):
        return Obj(f, "Object", permissive=True, label=p)
    return Obj(f, "Blueprint", label=p)


def _create_asset(f, _tools, *args, **kw):
    a = list(args) + [kw.get(k) for k in ("asset_name", "package_path", "asset_class", "factory")][len(args):]
    name, path, cls, fac = (a + [None] * 4)[:4]
    if isinstance(cls, Cls):
        return Obj(f, cls._name, label=f"{path}/{name}")
    return Obj(f, "Blueprint", label=f"{path}/{name}")


def _load_class(f, outer, name, *rest, **kw):
    if "/Script/FicsitAIHelper." in name and not STATE["mod_compiled"]:
        return None
    return Obj(f, "Object", permissive=True, label=name.split(".")[-1])


def _load_object(f, outer, name, *rest, **kw):
    if "/Script/FicsitAIHelper." in str(name):
        return Obj(f, "ScriptStruct", label=str(name)) if STATE["mod_compiled"] else None
    return _typed_by_path(f, name)


def _create_expr(f, *args, **kw):
    cls = args[1] if len(args) > 1 else kw.get("expression_class")
    return Obj(f, cls._name if isinstance(cls, Cls) else "MaterialExpression", label="expr")


def _find_socket(f, mesh, name, *a, **k):
    return Obj(f, "StaticMeshSocket", label=str(name))


SCENARIO = {
    "MaterialEditingLibrary.create_material_expression": _create_expr,
    "StaticMesh.find_socket": _find_socket,
    "EditorAssetLibrary.does_asset_exist": lambda f, *a, **k: False,
    "AssetToolsHelpers.get_asset_tools": lambda f, *a, **k: Obj(f, "AssetTools"),
    "AssetTools.create_asset": _create_asset,
    "BlueprintEditorLibrary.generated_class": lambda f, bp, *a, **k: Obj(f, "Object", permissive=True,
                                                                         label=bp._label.rsplit("/", 1)[-1] + "_C"),
    "EditorAssetLibrary.load_blueprint_class": lambda f, p, *a, **k: Obj(f, "Object", permissive=True, label=p + "_C"),
}
STATE = {"mod_compiled": False}


def install(idx, rep):
    f = Fake(idx, rep)
    mod = types.ModuleType("unreal")

    def getattr_(name):
        if name in GAME_NAMES:
            return Cls(f, name, permissive=True)
        if name in idx["classes"]:
            return Cls(f, name)
        if name in idx["funcs"]:
            impl = {"load_asset": lambda p, *a, **k: _typed_by_path(f, p),
                    "load_class": lambda *a, **k: _load_class(f, *a, **k),
                    "load_object": lambda *a, **k: _load_object(f, *a, **k),
                    "get_default_object": lambda c, *a, **k: Obj(f, "Object", permissive=True,
                                                                  label=f"CDO({getattr(c, '_label', c)})"),
                    "new_object": lambda c, *a, **k: Obj(f, "Object", permissive=True,
                                                         label=f"new({getattr(c, '_label', c)})"),
                    "get_editor_subsystem": lambda c, *a, **k: Obj(f, c._name),
                    "log": lambda *a, **k: None,
                    "log_warning": lambda *a, **k: print("    [W]", *a),
                    "log_error": lambda *a, **k: print("    [E]", *a)}.get(name)
            return Callable_(f, name, idx["funcs"][name] or {"args": [], "ndefaults": 0, "kwonly": [], "varargs": True,
                                                             "varkw": True, "ret": "Any"}, impl=impl)
        rep.err(f"unreal.{name}: not in UE 5.6")
        raise AttributeError(name)

    mod.__getattr__ = getattr_
    sys.modules["unreal"] = mod
    return f


# ------------------------------------------------------------------------------------------------------- run
def prepare(work, script):
    """Copy the script's folder (*.py, *.json, sub-folders except tools/Source) to work/<folder> and link everything
    next to that folder (textures/, export/, nodes.json, ...) into work, so relative paths resolve as in the repo."""
    src_dir = os.path.dirname(os.path.abspath(script))
    art = os.path.dirname(src_dir)
    dst = os.path.join(work, os.path.basename(src_dir))
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    os.makedirs(dst)
    for n in os.listdir(src_dir):
        p = os.path.join(src_dir, n)
        if n.endswith((".py", ".json")):
            shutil.copy2(p, dst)
        elif os.path.isdir(p) and n not in ("tools", "Source", "__pycache__"):
            shutil.copytree(p, os.path.join(dst, n))
    for n in os.listdir(art):
        link = os.path.join(work, n)
        if n != os.path.basename(src_dir) and not os.path.lexists(link):
            os.symlink(os.path.join(art, n), link)
    return os.path.join(dst, os.path.basename(script))


def run_mode(script, args):
    sys.argv = [script] + args
    code = compile(open(script, encoding="utf-8").read(), script, "exec")
    exec(code, {"__name__": "__main__", "__file__": script})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stub", required=True)
    ap.add_argument("--headers", nargs="*", default=[],
                    help="C++ header roots (SML FactoryGame/Public, the mod Source) to check the game property names")
    ap.add_argument("--work", default=os.path.join(os.environ.get("TMPDIR", "/tmp"), "cc_ue_dryrun"))
    ap.add_argument("--script", default=os.path.join(UE_DIR, "ue_import_command_center.py"))
    ap.add_argument("--modes", default="--discover,--import,--content,--verify")
    ap.add_argument("--compiled-modes", default="--content,--verify",
                    help="modes run a second time as if the C++ module were compiled")
    a = ap.parse_args()
    idx = build_index(a.stub)
    print(f"stub: {len(idx['classes'])} classes, {len(idx['funcs'])} functions ({a.stub})")
    script = prepare(a.work, a.script)
    rep = Report()
    install(idx, rep)
    summary = {}
    for compiled in (False, True):
        STATE["mod_compiled"] = compiled
        for mode in a.modes.split(","):
            tag = f"{mode}{' (C++ compiled)' if compiled else ''}"
            if compiled and mode not in a.compiled_modes.split(","):
                continue
            print(f"== {tag}")
            try:
                run_mode(script, [mode])
                steps = os.path.join(os.path.dirname(script), "ue_manual_steps.txt")
                n = len(open(steps, encoding="utf-8").read().splitlines()) if os.path.exists(steps) else 0
                if os.path.exists(steps):
                    os.remove(steps)
                summary[tag] = f"ok, {n} manual step(s)"
            except Exception as e:                           # noqa: BLE001 — report and continue
                summary[tag] = f"CRASH {type(e).__name__}: {e}"
                import traceback
                traceback.print_exc()
    print("\n== summary")
    for k, v in summary.items():
        print(f"  {k:28s} {v}")
    print(f"  engine API calls checked: {len(rep.calls)}")
    gp = sorted(set(rep.game_props))
    print(f"  FactoryGame / mod properties set ({len(gp)}): " + ", ".join(gp))
    print(f"  API mismatches: {len(rep.errors)}")
    for e in rep.errors:
        print("   - " + e)
    missing = []
    if a.headers:
        decl = set()
        for root in a.headers:
            for d, _, files in os.walk(root):
                for fn in files:
                    if fn.endswith(".h"):
                        txt = open(os.path.join(d, fn), encoding="utf-8", errors="replace").read()
                        decl |= {x.lower() for x in re.findall(r"(\w+)\s*(?::\s*\d+\s*)?(?:=[^;\n]*)?;", txt)}
        for g in gp:
            name = g.rsplit(".", 1)[-1]
            cpp = name.replace("_", "").lower()                      # m_display_name -> mdisplayname ~ mDisplayName
            if cpp not in decl:
                missing.append(name)
        print(f"  game properties not declared in the given headers: {len(missing)} {missing}")
    out = {"summary": summary, "api_calls": sorted(rep.calls), "game_props": gp, "errors": rep.errors}
    json.dump(out, open(os.path.join(a.work, "dryrun_report.json"), "w"), indent=2)
    crashed = any(v.startswith("CRASH") for v in summary.values())
    return 1 if rep.errors or crashed or missing else 0


if __name__ == "__main__":
    sys.exit(main())
