import type { Tool } from "@modelcontextprotocol/sdk/types.js";

/**
 * Белый список инструментов модели (S2, задача #10; ADR-018, ARCHITECTURE §3.3).
 *
 * Правило архитектуры: модели видны операции мода и те инструменты `sf-mcp`, у
 * которых есть ручной путь в игровом UI. Остальные скрыты, потому что дублируют
 * живые операции мода, и модель получила бы два разных ответа на один вопрос.
 *
 * **Список запрета, а не разрешения.** Разрешать поимённо было бы строже, но
 * тогда каждый новый инструмент `sf-mcp` после обновления Foreman молча исчезал
 * бы из чата, а мы узнавали бы об этом от игрока. Запрет перечисляет то, что мы
 * разобрали и решили спрятать; незнакомое имя проходит и попадает в лог
 * (`tools/list`), то есть становится видно нам, а не ломает ответ.
 *
 * Скрывать инструменты можно только вместе со своим системным промптом
 * (`SYSTEM_PROMPT_PATH`, `third_party/foreman/SYSTEM_PROMPT.md`): штатный промпт
 * Foreman обещает модели инструменты поимённо, и обещание несуществующего
 * инструмента заканчивается ходом без ответа. Совпадение промпта со списком
 * проверяется тестом `test/whitelist.test.ts`.
 */

/**
 * Инструменты чтения загруженного `.sav`.
 *
 * Прячутся не «на будущее», а потому что сейчас отвечают неправильно: playthrough
 * адаптера сохранение не несёт (`savePath` мы не передаём и не будем — §10), а
 * без него `sf-mcp` берёт склад по умолчанию из `SAVE_FILE_PATH`
 * (`store/registry.ts`). На машине разработчика это чужая игра, у игрока —
 * отсутствующий файл: в первом случае модель уверенно расскажет про чужой мир,
 * во втором ход сорвётся на ошибке инструмента. Живое состояние придёт от мода
 * (V-3), и тогда эти имена остаются скрытыми уже по §3.3.
 */
export const HIDDEN_SAVE_TOOLS = [
  "get_player_state",
  "get_unlocked_recipes",
  "get_milestones",
  "get_storage",
  "get_collectibles",
  "get_collected_identities",
  "get_nearby",
  "get_nearby_parts",
  "get_production",
  "check_material_coverage",
  "get_power",
  "find_bottlenecks",
  "describe_save",
] as const;

/**
 * Инструменты справочных данных игры: остаются видимыми в v0.1.
 *
 * §3.3 называет их в числе скрываемых, но там же (§3.4) встроенные данные
 * Foreman оставлены для справочных ответов, пока игра не подключена, а ADR-018
 * запрещает показывать инструмент раньше ручного пути — не прятать раньше
 * замены он не требует. Замена — `compute_plan` и реестр операций (V-3,
 * Milestone 2), в v0.1 их нет: спрятав расчёт сейчас, мы получим ассистента,
 * который считает по памяти, — ровно та ошибка, ради которой инструменты и
 * заведены. Поэтому прячем их не сейчас, а вместе с реестром: достаточно
 * перенести имена отсюда в список запрета (и убрать из промпта — тест не даст
 * забыть). Расхождение между §3.3 и таблицей вех §13 вынесено вопросом Co2-24.
 */
export const DEFERRED_PLANNER_TOOLS = [
  "ingredient_tree",
  "full_production_line",
  "total_raw_inputs",
  "compare_alternates",
] as const;

const HIDDEN = new Set<string>(HIDDEN_SAVE_TOOLS);

/** Скрыт ли инструмент `sf-mcp` от модели. */
export function isHidden(name: string): boolean {
  return HIDDEN.has(name);
}

/**
 * Причина отказа на вызов скрытого инструмента, иначе `undefined`.
 *
 * Отдельной функцией, потому что отказ — это решение белого списка, а не
 * деталь MCP-обработчика: модель может позвать инструмент, которого нет в
 * списке, по памяти о чужом промпте, и тихо пробросить такой вызов — значит
 * соблюсти список на словах и нарушить по сути.
 */
export function hiddenCallRefusal(name: string): string | undefined {
  if (!isHidden(name)) return undefined;
  return `инструмент «${name}» недоступен: он скрыт белым списком адаптера`;
}

/** Имена всех скрытых инструментов — для тестов и для README. */
export function hiddenToolNames(): string[] {
  return [...HIDDEN].sort();
}

/** Отбрасывает скрытые инструменты из списка `sf-mcp`. */
export function applyWhitelist(tools: Tool[]): Tool[] {
  return tools.filter((tool) => !isHidden(tool.name));
}
