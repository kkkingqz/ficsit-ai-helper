import { autoMount } from "./main.js";

/**
 * Загрузчик страницы чата: единственный скрипт, который она подключает.
 *
 * Он существует из-за политики изоляции. Страницы в игре отдаются с
 * `script-src 'self'` (ARCHITECTURE §6.3.1, §12 п. 11), и под неё **не
 * проходит ни один встроенный скрипт** — ни карта импорта, ни вызов
 * `autoMount()` в разметке. Co нашёл это на прогоне S8 3.4 и принял решение:
 * CSP не ослабляем, все скрипты страницы — отдельными файлами с того же
 * источника (Co-128). Прежняя страница чата опиралась и на встроенную карту
 * импорта, и на встроенный модуль, то есть в игре не запускалась вовсе.
 *
 * Имя пакета фасада здесь не упоминается: карту импорта заменяет шаг сборки,
 * который переписывает `@ficsitai/screens-api` в относительный путь
 * (`scripts/relink.mjs`, первый из двух путей Co-128).
 */
autoMount();

/**
 * Горячая перезагрузка — только вне игры.
 *
 * В игре этого файла нет, и запрос к нему дал бы 404 в консоли (замечание
 * Co-128). Признак игры — мост: `blu_event` на странице ставит мод, и в
 * браузере его не бывает. Динамический импорт, а не `<script src>` в
 * разметке, потому что условие в разметку не поставить без встроенного
 * скрипта. Отказ импорта гасим: вне dev-сервера файла тоже нет, и это не
 * повод ломать экран.
 */
if (typeof (globalThis as { blu_event?: unknown }).blu_event !== "function") {
  // Специфатор переменной: это адрес на странице, а не модуль в проекте, и
  // литерал `tsc` пытался бы разрешить на диске (TS2307).
  const reload: string = "/api/v0/reload.js";
  void import(reload).catch(() => undefined);
}
